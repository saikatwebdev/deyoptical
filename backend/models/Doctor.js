'use strict';

const mongoose = require('mongoose');

const doctorSchema = new mongoose.Schema(
  {
    // Slug-style stable id (e.g. 'dr-soumen') — matches frontend data
    doctorId: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    name: {
      type: String,
      required: [true, 'Doctor name is required'],
      trim: true,
    },
    title: { type: String, trim: true, default: '' },
    degree: { type: String, trim: true, default: '' },
    hospital: { type: String, trim: true, default: '' },

    // Schedule fields (admin editable)
    scheduleDay: { type: String, trim: true, default: '' },
    nextDate: { type: String, trim: true, default: '' },
    scheduleTime: { type: String, trim: true, default: '' },
    scheduleBadge: { type: String, trim: true, default: '' },

    // Availability (admin editable)
    availabilityStatus: {
      type: String,
      enum: ['available', 'limited', 'full', 'leave'],
      default: 'available',
    },
    availabilityLabel: { type: String, trim: true, default: 'Booking Open' },
    notice: { type: String, trim: true, default: '' },

    // Static display fields
    photo: { type: String, trim: true, default: '' },
    badgeColor: { type: String, trim: true, default: 'bg-primary/95' },
    highlights: [{ type: String, trim: true }],

    // Pre-encoded WhatsApp message (auto-generated by the frontend helper)
    whatsappMsg: { type: String, default: '' },

    // Display order
    order: { type: Number, default: 0 },
  },
  {
    timestamps: true,
    id: false,
  }
);

doctorSchema.virtual('id').get(function () {
  return this.doctorId || this._id?.toString();
});

doctorSchema.set('toJSON', {
  virtuals: true,
  transform: (_doc, ret) => {
    ret.id = ret.doctorId || ret._id?.toString();
    if (ret._id) ret._id = ret._id.toString();
    delete ret.__v;
    return ret;
  },
});

module.exports = mongoose.model('Doctor', doctorSchema);

