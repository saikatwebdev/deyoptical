import React, { useState, useCallback, useMemo, memo } from 'react';
import { useAdminData } from '../context/AdminDataContext.jsx';
import { generateDoctorWhatsAppMsg } from '../data/doctorsData.js';

export default function AdminPanelModal() {
  const {
    isAdminOpen,
    closeAdmin,
    isAuthenticated,
    login,
    logout,
    changePasscode,
    offers,
    addOffer,
    updateOffer,
    deleteOffer,
    toggleOffer,
    resetOffers,
    doctors,
    updateDoctor,
    resetDoctors,
    resetAllData,
  } = useAdminData();

  const [activeTab, setActiveTab] = useState('offers'); // 'offers' | 'doctors' | 'settings'

  // Auth form state
  const [pinInput, setPinInput] = useState('');
  const [pinError, setPinError] = useState('');
  const [showPin, setShowPin] = useState(false);

  // Offers edit/create modal state
  const [editingOffer, setEditingOffer] = useState(null); // null or offer object
  const [isCreatingOffer, setIsCreatingOffer] = useState(false);
  const [offerForm, setOfferForm] = useState({
    title: '',
    badge: 'SPECIAL DEAL',
    description: '',
    validTill: 'Valid this month',
    whatsappMessage: '',
    active: true,
  });

  // Doctor editing state
  const [selectedDoctorId, setSelectedDoctorId] = useState('dr-soumen');
  const [doctorSavedToast, setDoctorSavedToast] = useState('');

  // Security tab state
  const [newPin, setNewPin] = useState('');
  const [confirmPin, setConfirmPin] = useState('');
  const [pinChangeMsg, setPinChangeMsg] = useState({ type: '', text: '' });

  // Handle Login
  const handleLoginSubmit = (e) => {
    e.preventDefault();
    if (!pinInput.trim()) {
      setPinError('Please enter your admin passcode.');
      return;
    }
    const success = login(pinInput);
    if (success) {
      setPinError('');
      setPinInput('');
    } else {
      setPinError('Incorrect passcode. Please try again.');
    }
  };

  // Start Adding an Offer
  const handleStartAddOffer = () => {
    setOfferForm({
      title: '',
      badge: 'SPECIAL DEAL',
      description: '',
      validTill: 'Valid this month',
      whatsappMessage: '',
      active: true,
    });
    setIsCreatingOffer(true);
    setEditingOffer(null);
  };

  // Start Editing an Offer
  const handleStartEditOffer = (offer) => {
    setOfferForm({
      title: offer.title || '',
      badge: offer.badge || 'SPECIAL DEAL',
      description: offer.description || '',
      validTill: offer.validTill || '',
      whatsappMessage: offer.whatsappMessage || '',
      active: offer.active ?? true,
    });
    setEditingOffer(offer);
    setIsCreatingOffer(false);
  };

  // Save Offer (Add or Update)
  const handleSaveOffer = (e) => {
    e.preventDefault();
    if (!offerForm.title.trim() || !offerForm.description.trim()) {
      alert('Please provide at least an offer title and description.');
      return;
    }

    const finalMsg = offerForm.whatsappMessage.trim() ||
      `Hello Dey Optical! 👋\n\nI'm interested in the *${offerForm.title}* offer.\n\nPlease share details and availability.\n\nThank you!`;

    if (isCreatingOffer) {
      addOffer({
        title: offerForm.title.trim(),
        badge: offerForm.badge.trim() || 'OFFER',
        description: offerForm.description.trim(),
        validTill: offerForm.validTill.trim() || 'Limited Time',
        whatsappMessage: finalMsg,
        active: offerForm.active,
      });
    } else if (editingOffer) {
      updateOffer(editingOffer.id, {
        title: offerForm.title.trim(),
        badge: offerForm.badge.trim() || 'OFFER',
        description: offerForm.description.trim(),
        validTill: offerForm.validTill.trim() || 'Limited Time',
        whatsappMessage: finalMsg,
        active: offerForm.active,
      });
    }

    setIsCreatingOffer(false);
    setEditingOffer(null);
  };

  // Active Doctor to edit
  const currentDoctor = useMemo(() => {
    return doctors.find((d) => d.id === selectedDoctorId) || doctors[0];
  }, [doctors, selectedDoctorId]);

  // Handle Doctor Field Update
  const handleDoctorChange = (field, value) => {
    if (!currentDoctor) return;
    const updated = { [field]: value };

    // Auto-update availabilityLabel when status changes
    if (field === 'availabilityStatus') {
      if (value === 'available') updated.availabilityLabel = 'Booking Open';
      if (value === 'limited') updated.availabilityLabel = 'Fast Filling (Few Slots)';
      if (value === 'full') updated.availabilityLabel = 'Chamber Full';
      if (value === 'leave') updated.availabilityLabel = 'Doctor on Leave';
    }

    updateDoctor(currentDoctor.id, updated);
  };

  // Auto-generate Doctor WhatsApp message based on current schedule
  const handleAutoGenerateDoctorWa = () => {
    if (!currentDoctor) return;
    const freshMsg = decodeURIComponent(generateDoctorWhatsAppMsg(currentDoctor));
    updateDoctor(currentDoctor.id, { whatsappMsg: encodeURIComponent(freshMsg) });
    setDoctorSavedToast('WhatsApp message synced with current schedule!');
    setTimeout(() => setDoctorSavedToast(''), 3000);
  };

  // Change Admin PIN
  const handleChangePinSubmit = (e) => {
    e.preventDefault();
    if (!newPin || newPin.length < 4) {
      setPinChangeMsg({ type: 'error', text: 'Passcode must be at least 4 characters.' });
      return;
    }
    if (newPin !== confirmPin) {
      setPinChangeMsg({ type: 'error', text: 'New passcode and confirm passcode do not match.' });
      return;
    }
    const ok = changePasscode(newPin);
    if (ok) {
      setPinChangeMsg({ type: 'success', text: 'Admin passcode successfully changed!' });
      setNewPin('');
      setConfirmPin('');
      setTimeout(() => setPinChangeMsg({ type: '', text: '' }), 4000);
    }
  };

  // Export JSON backup
  const handleExportBackup = () => {
    const backupData = {
      exportedAt: new Date().toISOString(),
      offers,
      doctors,
    };
    const blob = new Blob([JSON.stringify(backupData, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `dey_optical_backup_${new Date().toISOString().slice(0, 10)}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  if (!isAdminOpen) return null;

  return (
    <div className="fixed inset-0 z-[100] flex items-center justify-center p-3 sm:p-5 bg-black/75 backdrop-blur-md overflow-y-auto">
      {/* ── Lock Screen / Authentication Card ── */}
      {!isAuthenticated ? (
        <div className="relative w-full max-w-md bg-white rounded-3xl shadow-2xl border border-gray-200 p-6 sm:p-8 text-on-surface animate-fade-in my-auto">
          {/* Close button */}
          <button
            onClick={closeAdmin}
            className="absolute top-4 right-4 w-9 h-9 rounded-full bg-gray-100 hover:bg-gray-200 flex items-center justify-center transition-colors cursor-pointer text-gray-500 hover:text-gray-800"
            aria-label="Close Admin Modal"
          >
            <span className="material-symbols-outlined text-[20px]">close</span>
          </button>

          <div className="text-center mb-6">
            <div className="w-14 h-14 rounded-2xl bg-primary/10 border border-primary/20 text-primary flex items-center justify-center mx-auto mb-3 shadow-inner">
              <span className="material-symbols-outlined text-[32px]" style={{ fontVariationSettings: "'FILL' 1" }}>
                shield_person
              </span>
            </div>
            <h2 className="text-2xl font-bold text-gray-900 tracking-tight">Dey Optical Admin</h2>
            <p className="text-[13px] text-gray-500 mt-1">
              Owner portal to update Offers &amp; Doctor Chamber schedules
            </p>
          </div>

          <form onSubmit={handleLoginSubmit} className="space-y-4">
            <div>
              <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                Admin Passcode
              </label>
              <div className="relative">
                <input
                  type={showPin ? 'text' : 'password'}
                  value={pinInput}
                  onChange={(e) => {
                    setPinInput(e.target.value);
                    setPinError('');
                  }}
                  placeholder="Enter passcode"
                  autoFocus
                  className="w-full px-4 py-3 rounded-xl border border-gray-300 focus:outline-none focus:ring-2 focus:ring-primary focus:border-transparent text-sm font-medium pr-10"
                />
                <button
                  type="button"
                  onClick={() => setShowPin(!showPin)}
                  className="absolute right-3 top-1/2 -translate-y-1/2 text-gray-400 hover:text-gray-600 cursor-pointer"
                >
                  <span className="material-symbols-outlined text-[20px]">
                    {showPin ? 'visibility_off' : 'visibility'}
                  </span>
                </button>
              </div>
              {pinError && <p className="text-xs text-red-600 font-semibold mt-1.5">{pinError}</p>}
            </div>

            <button
              type="submit"
              className="w-full py-3.5 rounded-xl bg-primary hover:bg-primary/95 text-white font-bold text-sm shadow-md transition-all active:scale-98 flex items-center justify-center gap-2 cursor-pointer"
            >
              <span className="material-symbols-outlined text-[18px]">lock_open</span>
              <span>Access Admin Dashboard</span>
            </button>
          </form>

          <div className="mt-6 pt-4 border-t border-gray-100 text-center">
            <p className="text-[11px] text-gray-400">
              Authorized personnel &amp; store management access only
            </p>
          </div>
        </div>
      ) : (
        /* ── Full Admin Dashboard ── */
        <div className="relative w-full max-w-5xl bg-white rounded-3xl shadow-2xl border border-gray-200 overflow-hidden flex flex-col max-h-[92vh] my-auto">
          {/* Header */}
          <div className="px-6 py-4 bg-gray-900 text-white flex items-center justify-between flex-wrap gap-3 border-b border-gray-800 flex-shrink-0">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 rounded-xl bg-primary flex items-center justify-center text-white shadow-sm flex-shrink-0">
                <span className="material-symbols-outlined text-[22px]" style={{ fontVariationSettings: "'FILL' 1" }}>
                  admin_panel_settings
                </span>
              </div>
              <div>
                <div className="flex items-center gap-2">
                  <h2 className="text-lg font-bold leading-tight">Dey Optical Admin Portal</h2>
                  <span className="inline-flex items-center gap-1 bg-emerald-500/20 text-emerald-300 border border-emerald-500/30 text-[10px] font-bold px-2 py-0.5 rounded-full">
                    <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 animate-pulse" />
                    Live Sync Active
                  </span>
                </div>
                <p className="text-[11px] text-gray-400">Instant website updates · Beliatore Chamber</p>
              </div>
            </div>

            <div className="flex items-center gap-2">
              <button
                onClick={closeAdmin}
                className="px-3.5 py-1.5 rounded-xl bg-gray-800 hover:bg-gray-700 text-gray-200 text-xs font-semibold flex items-center gap-1.5 transition-colors cursor-pointer"
                title="Return to website preview"
              >
                <span className="material-symbols-outlined text-[16px]">visibility</span>
                <span className="hidden sm:inline">View Website</span>
              </button>
              <button
                onClick={logout}
                className="px-3 py-1.5 rounded-xl bg-red-600/20 hover:bg-red-600/30 text-red-300 border border-red-500/30 text-xs font-semibold flex items-center gap-1 transition-colors cursor-pointer"
                title="Log out from admin"
              >
                <span className="material-symbols-outlined text-[16px]">logout</span>
                <span className="hidden sm:inline">Log Out</span>
              </button>
              <button
                onClick={closeAdmin}
                className="w-8 h-8 rounded-full bg-gray-800 hover:bg-gray-700 flex items-center justify-center text-gray-300 hover:text-white transition-colors cursor-pointer ml-1"
                aria-label="Close"
              >
                <span className="material-symbols-outlined text-[18px]">close</span>
              </button>
            </div>
          </div>

          {/* Navigation Tabs */}
          <div className="flex items-center border-b border-gray-200 bg-gray-50/80 px-6 gap-2 overflow-x-auto flex-shrink-0">
            <button
              onClick={() => setActiveTab('offers')}
              className={`py-3.5 px-4 font-bold text-xs uppercase tracking-wider flex items-center gap-2 border-b-2 transition-all cursor-pointer whitespace-nowrap ${
                activeTab === 'offers'
                  ? 'border-primary text-primary bg-white shadow-xs rounded-t-xl'
                  : 'border-transparent text-gray-500 hover:text-gray-800'
              }`}
            >
              <span className="text-[16px]">🎉</span>
              <span>1. Special Offers ({offers.length})</span>
            </button>
            <button
              onClick={() => setActiveTab('doctors')}
              className={`py-3.5 px-4 font-bold text-xs uppercase tracking-wider flex items-center gap-2 border-b-2 transition-all cursor-pointer whitespace-nowrap ${
                activeTab === 'doctors'
                  ? 'border-primary text-primary bg-white shadow-xs rounded-t-xl'
                  : 'border-transparent text-gray-500 hover:text-gray-800'
              }`}
            >
              <span className="text-[16px]">👨‍⚕️</span>
              <span>2. Eye Specialist Timing &amp; Availability</span>
            </button>
            <button
              onClick={() => setActiveTab('settings')}
              className={`py-3.5 px-4 font-bold text-xs uppercase tracking-wider flex items-center gap-2 border-b-2 transition-all cursor-pointer whitespace-nowrap ${
                activeTab === 'settings'
                  ? 'border-primary text-primary bg-white shadow-xs rounded-t-xl'
                  : 'border-transparent text-gray-500 hover:text-gray-800'
              }`}
            >
              <span className="material-symbols-outlined text-[18px]">settings</span>
              <span>3. Passcode &amp; Backups</span>
            </button>
          </div>

          {/* Tab Content Area (Scrollable) */}
          <div className="flex-1 overflow-y-auto p-4 sm:p-6 bg-gray-50/50">
            {/* ════════════ TAB 1: OFFERS MANAGER ════════════ */}
            {activeTab === 'offers' && (
              <div className="space-y-6">
                <div className="flex items-center justify-between flex-wrap gap-3 bg-white p-4 rounded-2xl border border-gray-200 shadow-xs">
                  <div>
                    <h3 className="font-bold text-gray-900 text-base">Promotional Offers &amp; Discounts</h3>
                    <p className="text-xs text-gray-500">
                      These offers appear inside the blinking floating offers button on the website.
                    </p>
                  </div>
                  <div className="flex items-center gap-2">
                    <button
                      onClick={handleStartAddOffer}
                      className="px-4 py-2.5 rounded-xl bg-primary text-white font-bold text-xs flex items-center gap-1.5 shadow-sm hover:bg-primary/90 transition-all cursor-pointer"
                    >
                      <span className="material-symbols-outlined text-[18px]">add_circle</span>
                      <span>Add New Offer</span>
                    </button>
                    <button
                      onClick={() => {
                        if (confirm('Reset offers to initial defaults?')) resetOffers();
                      }}
                      className="px-3 py-2 rounded-xl border border-gray-300 text-gray-600 hover:bg-gray-100 font-semibold text-xs transition-colors cursor-pointer"
                      title="Reset offers to initial list"
                    >
                      Reset Defaults
                    </button>
                  </div>
                </div>

                {/* Offer Cards List */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                  {offers.map((offer) => (
                    <div
                      key={offer.id}
                      className={`relative rounded-2xl border p-4 sm:p-5 transition-all bg-white shadow-xs ${
                        offer.active ? 'border-gray-200' : 'border-dashed border-gray-300 opacity-60 bg-gray-50'
                      }`}
                    >
                      <div className="flex items-start justify-between gap-2 mb-2">
                        <div className="flex items-center gap-2 flex-wrap">
                          <span className="bg-red-600 text-white text-[10px] font-bold tracking-wider uppercase px-2.5 py-0.5 rounded-full">
                            {offer.badge}
                          </span>
                          <span className="text-[11px] text-gray-500 font-medium">{offer.validTill}</span>
                        </div>
                        {/* Active toggle */}
                        <button
                          type="button"
                          onClick={() => toggleOffer(offer.id)}
                          className={`text-[11px] font-bold px-2.5 py-1 rounded-full border transition-all cursor-pointer flex items-center gap-1 ${
                            offer.active
                              ? 'bg-emerald-50 text-emerald-700 border-emerald-300 hover:bg-emerald-100'
                              : 'bg-gray-100 text-gray-500 border-gray-300 hover:bg-gray-200'
                          }`}
                        >
                          <span className={`w-1.5 h-1.5 rounded-full ${offer.active ? 'bg-emerald-500' : 'bg-gray-400'}`} />
                          {offer.active ? 'Live' : 'Hidden'}
                        </button>
                      </div>

                      <h4 className="font-bold text-gray-900 text-sm sm:text-base leading-snug mb-1">
                        {offer.title}
                      </h4>
                      <p className="text-xs text-gray-600 leading-relaxed line-clamp-2 mb-4">
                        {offer.description}
                      </p>

                      <div className="pt-3 border-t border-gray-100 flex items-center justify-between text-xs">
                        <span className="text-[11px] text-gray-400 truncate max-w-[180px]">
                          WhatsApp pre-fill configured
                        </span>
                        <div className="flex items-center gap-2">
                          <button
                            onClick={() => handleStartEditOffer(offer)}
                            className="px-3 py-1.5 rounded-lg bg-gray-100 hover:bg-gray-200 text-gray-700 font-bold text-xs flex items-center gap-1 transition-colors cursor-pointer"
                          >
                            <span className="material-symbols-outlined text-[14px]">edit</span>
                            Edit
                          </button>
                          <button
                            onClick={() => {
                              if (confirm(`Delete offer "${offer.title}"?`)) deleteOffer(offer.id);
                            }}
                            className="p-1.5 rounded-lg text-red-500 hover:bg-red-50 transition-colors cursor-pointer"
                            title="Delete Offer"
                          >
                            <span className="material-symbols-outlined text-[16px]">delete</span>
                          </button>
                        </div>
                      </div>
                    </div>
                  ))}
                </div>

                {offers.length === 0 && (
                  <div className="text-center py-12 bg-white rounded-2xl border border-gray-200">
                    <p className="text-sm text-gray-500 font-medium">No offers currently created.</p>
                    <button
                      onClick={handleStartAddOffer}
                      className="mt-3 px-4 py-2 bg-primary text-white text-xs font-bold rounded-xl shadow-xs"
                    >
                      Create First Offer
                    </button>
                  </div>
                )}
              </div>
            )}

            {/* ════════════ TAB 2: EYE SPECIALIST SCHEDULE & AVAILABILITY ════════════ */}
            {activeTab === 'doctors' && (
              <div className="space-y-6">
                {/* Doctor Selection Pill Selector */}
                <div className="bg-white p-4 rounded-2xl border border-gray-200 shadow-xs flex items-center justify-between flex-wrap gap-3">
                  <div>
                    <h3 className="font-bold text-gray-900 text-base">Eye Specialist Chamber &amp; Availability</h3>
                    <p className="text-xs text-gray-500">
                      Update visiting days, next specific dates, timings, availability badges, and WhatsApp notices.
                    </p>
                  </div>
                  <div className="flex items-center gap-2">
                    {doctors.map((doc) => (
                      <button
                        key={doc.id}
                        onClick={() => setSelectedDoctorId(doc.id)}
                        className={`px-4 py-2 rounded-xl font-bold text-xs flex items-center gap-2 transition-all cursor-pointer ${
                          selectedDoctorId === doc.id
                            ? 'bg-primary text-white shadow-sm'
                            : 'bg-gray-100 text-gray-700 hover:bg-gray-200'
                        }`}
                      >
                        <span className="w-2 h-2 rounded-full bg-emerald-400" />
                        <span>{doc.name.split(' ')[1]} ({doc.scheduleDay.replace('Every ', '')})</span>
                      </button>
                    ))}
                    <button
                      onClick={() => {
                        if (confirm('Reset doctors schedule to initial defaults?')) resetDoctors();
                      }}
                      className="px-3 py-2 rounded-xl border border-gray-300 text-gray-600 hover:bg-gray-100 font-semibold text-xs transition-colors cursor-pointer"
                      title="Reset doctor schedules to defaults"
                    >
                      Reset
                    </button>
                  </div>
                </div>

                {/* Toast Notification */}
                {doctorSavedToast && (
                  <div className="bg-emerald-500 text-white px-4 py-2.5 rounded-xl text-xs font-bold flex items-center gap-2 shadow-sm animate-fade-in">
                    <span className="material-symbols-outlined text-[18px]">check_circle</span>
                    <span>{doctorSavedToast}</span>
                  </div>
                )}

                {/* Edit Form for selected Doctor */}
                {currentDoctor && (
                  <div className="bg-white rounded-2xl border border-gray-200 p-5 sm:p-7 shadow-xs space-y-6">
                    {/* Doctor Header Banner */}
                    <div className="flex items-center gap-4 pb-6 border-b border-gray-100">
                      <img
                        src={currentDoctor.photo}
                        alt={currentDoctor.name}
                        className="w-16 h-16 sm:w-20 sm:h-20 rounded-2xl object-cover object-top border-2 border-primary/20 shadow-md flex-shrink-0"
                      />
                      <div>
                        <div className="flex items-center gap-2 flex-wrap">
                          <h4 className="text-xl font-bold text-gray-900 leading-tight">
                            {currentDoctor.name}
                          </h4>
                          <span className="bg-primary/10 text-primary font-bold text-[11px] px-2.5 py-0.5 rounded-full">
                            {currentDoctor.degree}
                          </span>
                        </div>
                        <p className="text-xs text-gray-500 font-medium mt-0.5">{currentDoctor.title}</p>
                        <p className="text-xs text-gray-400 flex items-center gap-1 mt-1">
                          <span className="material-symbols-outlined text-[14px]">local_hospital</span>
                          {currentDoctor.hospital}
                        </p>
                      </div>
                    </div>

                    {/* Schedule & Availability Fields */}
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-5">
                      {/* Availability Status */}
                      <div>
                        <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                          Availability Status
                        </label>
                        <select
                          value={currentDoctor.availabilityStatus || 'available'}
                          onChange={(e) => handleDoctorChange('availabilityStatus', e.target.value)}
                          className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 font-medium text-sm focus:outline-none focus:ring-2 focus:ring-primary bg-white cursor-pointer"
                        >
                          <option value="available">🟢 Available (Booking Open)</option>
                          <option value="limited">🟡 Few Slots Remaining (Fast Filling)</option>
                          <option value="full">🔴 Chamber Full / Housefull</option>
                          <option value="leave">⚪ Doctor on Leave / Next Date Below</option>
                        </select>
                        <p className="text-[11px] text-gray-400 mt-1">
                          Displays on the doctor's card badge and informs patients.
                        </p>
                      </div>

                      {/* Status Custom Label */}
                      <div>
                        <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                          Chamber Status Badge Text
                        </label>
                        <input
                          type="text"
                          value={currentDoctor.availabilityLabel || 'Booking Open'}
                          onChange={(e) => handleDoctorChange('availabilityLabel', e.target.value)}
                          placeholder="e.g. Booking Open, Few Slots Left, Next: 23 Nov"
                          className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 font-medium text-sm focus:outline-none focus:ring-2 focus:ring-primary"
                        />
                      </div>

                      {/* Recurring Schedule Day */}
                      <div>
                        <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                          Visiting Day (General Schedule)
                        </label>
                        <input
                          type="text"
                          value={currentDoctor.scheduleDay || ''}
                          onChange={(e) => handleDoctorChange('scheduleDay', e.target.value)}
                          placeholder="e.g. Every Sunday, Every Thursday"
                          className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 font-medium text-sm focus:outline-none focus:ring-2 focus:ring-primary"
                        />
                      </div>

                      {/* Next Specific Chamber Date */}
                      <div>
                        <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                          Next Upcoming Date
                        </label>
                        <input
                          type="text"
                          value={currentDoctor.nextDate || ''}
                          onChange={(e) => handleDoctorChange('nextDate', e.target.value)}
                          placeholder="e.g. Sunday, 23 Nov 2026"
                          className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 font-medium text-sm focus:outline-none focus:ring-2 focus:ring-primary"
                        />
                        <p className="text-[11px] text-gray-400 mt-1">
                          Specify the exact next date (e.g. "Sunday, 23 Nov 2026")
                        </p>
                      </div>

                      {/* Visiting Timing Slot */}
                      <div>
                        <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                          Visiting Timing Hours
                        </label>
                        <input
                          type="text"
                          value={currentDoctor.scheduleTime || ''}
                          onChange={(e) => handleDoctorChange('scheduleTime', e.target.value)}
                          placeholder="e.g. 11:30 AM – 1:00 PM"
                          className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 font-medium text-sm focus:outline-none focus:ring-2 focus:ring-primary"
                        />
                      </div>

                      {/* Corner Badge on Photo */}
                      <div>
                        <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                          Photo Corner Badge
                        </label>
                        <input
                          type="text"
                          value={currentDoctor.scheduleBadge || ''}
                          onChange={(e) => handleDoctorChange('scheduleBadge', e.target.value)}
                          placeholder="e.g. Every Sunday or Next: 23 Nov"
                          className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 font-medium text-sm focus:outline-none focus:ring-2 focus:ring-primary"
                        />
                      </div>
                    </div>

                    {/* Special Chamber Notice / Announcement */}
                    <div>
                      <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1.5">
                        Chamber Notice / Announcement (Optional)
                      </label>
                      <input
                        type="text"
                        value={currentDoctor.notice || ''}
                        onChange={(e) => handleDoctorChange('notice', e.target.value)}
                        placeholder="e.g. Free glaucoma screening for the first 10 patients this week!"
                        className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 font-medium text-sm focus:outline-none focus:ring-2 focus:ring-primary"
                      />
                    </div>

                    {/* WhatsApp Action Preview & Sync Button */}
                    <div className="bg-gray-50 p-4 rounded-xl border border-gray-200">
                      <div className="flex items-center justify-between flex-wrap gap-2 mb-2">
                        <span className="text-xs font-bold text-gray-700 uppercase tracking-wider flex items-center gap-1.5">
                          <span className="text-[#25D366] text-sm">●</span> WhatsApp Booking Message Pre-fill
                        </span>
                        <button
                          type="button"
                          onClick={handleAutoGenerateDoctorWa}
                          className="px-3 py-1.5 rounded-lg bg-emerald-600 hover:bg-emerald-700 text-white font-bold text-xs flex items-center gap-1 shadow-xs transition-colors cursor-pointer"
                        >
                          <span className="material-symbols-outlined text-[14px]">sync</span>
                          Auto-Generate from Schedule
                        </button>
                      </div>
                      <textarea
                        rows={5}
                        value={decodeURIComponent(currentDoctor.whatsappMsg || '')}
                        onChange={(e) => handleDoctorChange('whatsappMsg', encodeURIComponent(e.target.value))}
                        className="w-full p-3 rounded-lg border border-gray-300 font-mono text-xs focus:outline-none focus:ring-1 focus:ring-primary bg-white"
                      />
                      <p className="text-[11px] text-gray-400 mt-1">
                        This text is automatically loaded when a visitor clicks "Book Appointment with {currentDoctor.name.split(' ')[1]}".
                      </p>
                    </div>

                    <div className="flex items-center justify-end">
                      <div className="inline-flex items-center gap-1.5 text-xs text-emerald-600 font-bold bg-emerald-50 px-3 py-1.5 rounded-lg">
                        <span className="material-symbols-outlined text-[16px]">check</span>
                        Changes save immediately to live website
                      </div>
                    </div>
                  </div>
                )}
              </div>
            )}

            {/* ════════════ TAB 3: SECURITY & SETTINGS ════════════ */}
            {activeTab === 'settings' && (
              <div className="space-y-6 max-w-2xl mx-auto">
                {/* Change Passcode Card */}
                <div className="bg-white p-6 rounded-2xl border border-gray-200 shadow-xs">
                  <div className="flex items-center gap-2.5 mb-4">
                    <span className="w-8 h-8 rounded-lg bg-primary/10 text-primary flex items-center justify-center">
                      <span className="material-symbols-outlined text-[18px]">key</span>
                    </span>
                    <div>
                      <h4 className="font-bold text-gray-900 text-sm">Change Admin Passcode</h4>
                      <p className="text-xs text-gray-500">Update the passcode required to access this portal.</p>
                    </div>
                  </div>

                  <form onSubmit={handleChangePinSubmit} className="space-y-3.5">
                    <div>
                      <label className="block text-xs font-semibold text-gray-700 mb-1">New Passcode</label>
                      <input
                        type="password"
                        value={newPin}
                        onChange={(e) => setNewPin(e.target.value)}
                        placeholder="At least 4 characters"
                        className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 text-sm focus:outline-none focus:ring-2 focus:ring-primary font-medium"
                      />
                    </div>
                    <div>
                      <label className="block text-xs font-semibold text-gray-700 mb-1">Confirm New Passcode</label>
                      <input
                        type="password"
                        value={confirmPin}
                        onChange={(e) => setConfirmPin(e.target.value)}
                        placeholder="Re-type new passcode"
                        className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 text-sm focus:outline-none focus:ring-2 focus:ring-primary font-medium"
                      />
                    </div>

                    {pinChangeMsg.text && (
                      <p className={`text-xs font-semibold ${pinChangeMsg.type === 'error' ? 'text-red-600' : 'text-emerald-600'}`}>
                        {pinChangeMsg.text}
                      </p>
                    )}

                    <button
                      type="submit"
                      className="px-5 py-2.5 rounded-xl bg-primary hover:bg-primary/95 text-white font-bold text-xs shadow-xs cursor-pointer"
                    >
                      Update Passcode
                    </button>
                  </form>
                </div>

                {/* Backup & Export Card */}
                <div className="bg-white p-6 rounded-2xl border border-gray-200 shadow-xs">
                  <div className="flex items-center gap-2.5 mb-2">
                    <span className="w-8 h-8 rounded-lg bg-emerald-50 text-emerald-600 flex items-center justify-center">
                      <span className="material-symbols-outlined text-[18px]">download</span>
                    </span>
                    <div>
                      <h4 className="font-bold text-gray-900 text-sm">Backup Configuration</h4>
                      <p className="text-xs text-gray-500">Download current offers and doctor schedules as a JSON file.</p>
                    </div>
                  </div>
                  <p className="text-xs text-gray-600 mb-4">
                    Keep a local backup copy of your custom offers and specialist chamber timings anytime you make significant changes.
                  </p>
                  <button
                    onClick={handleExportBackup}
                    className="px-4 py-2.5 rounded-xl border border-gray-300 hover:bg-gray-100 text-gray-800 font-bold text-xs flex items-center gap-1.5 transition-colors cursor-pointer"
                  >
                    <span className="material-symbols-outlined text-[16px]">file_download</span>
                    Download Backup JSON
                  </button>
                </div>

                {/* Factory Reset */}
                <div className="bg-red-50/50 p-6 rounded-2xl border border-red-200 shadow-xs">
                  <div className="flex items-center gap-2.5 mb-2">
                    <span className="w-8 h-8 rounded-lg bg-red-100 text-red-600 flex items-center justify-center">
                      <span className="material-symbols-outlined text-[18px]">restart_alt</span>
                    </span>
                    <div>
                      <h4 className="font-bold text-red-900 text-sm">Reset All Website Data</h4>
                      <p className="text-xs text-red-600">Reverts all special offers and doctor schedules to their original factory defaults.</p>
                    </div>
                  </div>
                  <button
                    onClick={() => {
                      if (confirm('Are you sure you want to revert both Offers and Doctors to initial defaults?')) {
                        resetAllData();
                        alert('All data restored to factory defaults!');
                      }
                    }}
                    className="mt-2 px-4 py-2.5 rounded-xl bg-red-600 hover:bg-red-700 text-white font-bold text-xs shadow-xs transition-colors cursor-pointer"
                  >
                    Reset Everything to Factory Defaults
                  </button>
                </div>
              </div>
            )}
          </div>
        </div>
      )}

      {/* ── Sub-modal for Creating or Editing an Offer ── */}
      {(isCreatingOffer || editingOffer) && (
        <div className="fixed inset-0 z-[110] flex items-center justify-center p-4 bg-black/60 backdrop-blur-xs animate-fade-in">
          <div className="w-full max-w-lg bg-white rounded-3xl shadow-2xl border border-gray-200 p-6 overflow-hidden max-h-[90vh] flex flex-col">
            <div className="flex items-center justify-between pb-4 border-b border-gray-100 mb-4">
              <h3 className="font-bold text-gray-900 text-base">
                {isCreatingOffer ? 'Add New Promotional Offer' : 'Edit Promotional Offer'}
              </h3>
              <button
                onClick={() => {
                  setIsCreatingOffer(false);
                  setEditingOffer(null);
                }}
                className="w-8 h-8 rounded-full bg-gray-100 hover:bg-gray-200 flex items-center justify-center text-gray-500 cursor-pointer"
              >
                <span className="material-symbols-outlined text-[18px]">close</span>
              </button>
            </div>

            <form onSubmit={handleSaveOffer} className="space-y-4 overflow-y-auto pr-1 flex-1">
              <div>
                <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1">
                  Offer Title
                </label>
                <input
                  type="text"
                  value={offerForm.title}
                  onChange={(e) => setOfferForm({ ...offerForm, title: e.target.value })}
                  placeholder="e.g. 🔥 Flat 30% OFF on All Eyeglasses"
                  required
                  className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 text-sm font-medium focus:outline-none focus:ring-2 focus:ring-primary"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1">
                    Badge Pill
                  </label>
                  <input
                    type="text"
                    value={offerForm.badge}
                    onChange={(e) => setOfferForm({ ...offerForm, badge: e.target.value })}
                    placeholder="e.g. LIMITED TIME, BOGO"
                    className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 text-sm font-medium focus:outline-none focus:ring-2 focus:ring-primary"
                  />
                </div>
                <div>
                  <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1">
                    Validity Text
                  </label>
                  <input
                    type="text"
                    value={offerForm.validTill}
                    onChange={(e) => setOfferForm({ ...offerForm, validTill: e.target.value })}
                    placeholder="e.g. Valid till 30 Nov 2026"
                    className="w-full px-3.5 py-2.5 rounded-xl border border-gray-300 text-sm font-medium focus:outline-none focus:ring-2 focus:ring-primary"
                  />
                </div>
              </div>

              <div>
                <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1">
                  Offer Description
                </label>
                <textarea
                  rows={3}
                  value={offerForm.description}
                  onChange={(e) => setOfferForm({ ...offerForm, description: e.target.value })}
                  placeholder="Describe discounts, included brands, or conditions..."
                  required
                  className="w-full p-3 rounded-xl border border-gray-300 text-sm font-medium focus:outline-none focus:ring-2 focus:ring-primary"
                />
              </div>

              <div>
                <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider mb-1">
                  WhatsApp Message Template (Optional)
                </label>
                <textarea
                  rows={3}
                  value={offerForm.whatsappMessage}
                  onChange={(e) => setOfferForm({ ...offerForm, whatsappMessage: e.target.value })}
                  placeholder="Leave empty to use automatic greeting template..."
                  className="w-full p-3 rounded-xl border border-gray-300 font-mono text-xs focus:outline-none focus:ring-2 focus:ring-primary"
                />
              </div>

              <div className="flex items-center gap-2 pt-1">
                <input
                  type="checkbox"
                  id="offerActiveCheck"
                  checked={offerForm.active}
                  onChange={(e) => setOfferForm({ ...offerForm, active: e.target.checked })}
                  className="w-4 h-4 text-primary rounded border-gray-300 cursor-pointer"
                />
                <label htmlFor="offerActiveCheck" className="text-xs font-semibold text-gray-700 cursor-pointer">
                  Show this offer on the website immediately (Active)
                </label>
              </div>

              <div className="pt-3 border-t border-gray-100 flex items-center justify-end gap-2">
                <button
                  type="button"
                  onClick={() => {
                    setIsCreatingOffer(false);
                    setEditingOffer(null);
                  }}
                  className="px-4 py-2 rounded-xl border border-gray-300 text-gray-600 font-semibold text-xs cursor-pointer"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="px-5 py-2 rounded-xl bg-primary text-white font-bold text-xs shadow-xs hover:bg-primary/95 cursor-pointer"
                >
                  {isCreatingOffer ? 'Create Offer' : 'Save Changes'}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}

